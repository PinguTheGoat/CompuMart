-- CompuMart Supabase Schema & Seed Data
-- Run this in your Supabase SQL Editor (https://app.supabase.com -> SQL Editor)

-- 1. Products Table
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    image TEXT NOT NULL,
    category TEXT NOT NULL,
    description TEXT,
    stock INT DEFAULT 0,
    rating NUMERIC(2, 1) DEFAULT 4.8,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable Row Level Security (RLS)
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;

-- Allow public read access to products
CREATE POLICY "Allow public read access to products"
    ON public.products FOR SELECT
    USING (true);

-- Allow authenticated admins to insert/update/delete products
CREATE POLICY "Allow authenticated full access to products"
    ON public.products FOR ALL
    TO authenticated
    USING (true)
    WITH CHECK (true);

-- 2. Orders Table
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_email TEXT NOT NULL,
    customer_name TEXT,
    phone TEXT,
    address TEXT,
    total NUMERIC(10, 2) NOT NULL,
    status TEXT DEFAULT 'pending',
    items JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

-- Allow anyone to place an order
CREATE POLICY "Allow public insert to orders"
    ON public.orders FOR INSERT
    WITH CHECK (true);

-- Allow reading orders
CREATE POLICY "Allow authenticated read to orders"
    ON public.orders FOR SELECT
    USING (true);

